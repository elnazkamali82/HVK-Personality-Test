function polesOf(profile: Profile): Record<DomainId, Pole> {
  return Object.fromEntries(profile.domains.map((d) => [d.id, d.pole])) as Record<DomainId, Pole>;
}

function tagOf(profile: Profile, itemId: string): string {
  return profile.qualitative.find((item) => item.itemId === itemId)?.tag ?? "";
}

function note(tag: string): string {
  return NOTES[tag] ?? "";
}

function overview(profile: Profile): string {
  const ranked = [...profile.domains].sort((a, b) => b.index - a.index);
  const high = ranked[0]!;
  const low = ranked[ranked.length - 1]!;
  return `در میان پنج نمره خودتان، ${high.name} با ${fa(high.index)} پررنگ‌ترین محور این پاسخ‌هاست و ${low.name} با ${fa(low.index)} کم‌رنگ‌ترین. این مقایسه فقط درون پاسخ‌های شماست. هر عدد، تبدیل خطی میانگین گویه‌های همان عامل از مقیاس ۱ تا ۵ به بازه ۰ تا ۱۰۰ است.`;
}

function learningText(profile: Profile, pole: Record<DomainId, Pole>): string {
  if (pole.O === "high") {
    return `برای یادگیری چیز تازه، کنجکاوی در پاسخ‌ها از مرکز مقیاس بالاتر است. ${note(tagOf(profile, "q18"))}`;
  }
  if (pole.O === "low") {
    return `برای یادگیری چیز تازه، روش آشنا و کاربردی در پاسخ‌ها نزدیک‌تر است. ${note(tagOf(profile, "q18"))}`;
  }
  return `برای یادگیری چیز تازه، هم کنجکاوی و هم ترجیح روش آشنا در پاسخ‌ها هست. ${note(tagOf(profile, "q18"))}`;
}

function linesFor(
  profile: Profile,
  table: Partial<Record<DomainId, Record<Exclude<Pole, "mid">, string>>>,
): string[] {
  return profile.domains
    .filter((d) => d.pole !== "mid")
    .sort((a, b) => Math.abs(b.index - 50) - Math.abs(a.index - 50))
    .slice(0, 4)
    .map((d) => table[d.id]?.[d.pole as Exclude<Pole, "mid">])
    .filter((text): text is string => Boolean(text));
}

