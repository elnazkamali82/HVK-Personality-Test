export function funFor(domains: DomainScore[]): FunReport {
  const ranked = [...domains].sort((a, b) => b.index - a.index);
  const peak = ranked[0]!;
  const low = ranked[ranked.length - 1]!;
  const second = ranked[1]!;
  const pack =
    FUN_COMBOS[`${peak.id}-${low.id}`] ??
    FUN_COMBOS[`${peak.id}-${second.id}`] ??
    FUN_PEAK_FALLBACK[peak.id];

  return {
    voice: `با ${peak.name} روی ${fa(peak.index)} و ${low.name} روی ${fa(low.index)}، نیمرخت یک میدان مغناطیسی دارد: یک قطب می‌کشد، قطب دیگر ترمز می‌گیرد. همزادت از همین اصطکاک ساخته می‌شود.`,
    ...pack,
  };
}

export function isFunReport(value: unknown): value is FunReport {
  if (!value || typeof value !== "object") return false;
  const fun = value as FunReport;
  return Boolean(
    fun.voice &&
      fun.animal?.name &&
      fun.character?.name &&
      fun.food?.name &&
      fun.career?.name &&
      fun.place?.name,
  );
}

/** Complete or replace a missing/partial `fun` block. */
export function ensureFun(fun: unknown, domains: DomainScore[]): FunReport {
  return isFunReport(fun) ? fun : funFor(domains);
}

/** Fill missing `fun` when an older LLM/API payload omits it. */
export function normalizeReport(report: Report): Report {
  return { ...report, fun: ensureFun(report.fun, report.domains) };
}

export function buildReport(profile: Profile): Report {
  const pole = polesOf(profile);
  const conflict = tagOf(profile, "q06");
  const change = tagOf(profile, "q12");
  const help = tagOf(profile, "q24");
  const company = tagOf(profile, "q30");
  const decision = tagOf(profile, "q36");
  const companyDiverge =
    (pole.E === "high" && company === "solo") ||
    (pole.E === "low" && company === "interactive")
      ? " این انتخاب با جهت نمره برون‌گرایی یکی نیست."
      : "";

  return {
    overview: overview(profile),
    domains: profile.domains,
    domainTexts: profile.domains.map((domain) => ({
      id: domain.id,
      name: domain.name,
      text: DOMAIN_TEXT[domain.id][domain.pole],
    })),
    interactions: INTERACTIONS.filter((rule) => rule.test(pole)).map((rule) => rule.text),
    qualitative: [conflict, change, tagOf(profile, "q18"), help, company, decision].map(
      (tag) => `${note(tag)} این مشاهده در نمره پنج عامل وارد نشده است.`,
    ),
    groupBehavior: `${GROUP[`${pole.E}-${pole.A}`]} ${note(conflict)} ${note(company)}${companyDiverge} این دو مشاهده در نمره وارد نشده‌اند.`,
    difficulty: `${DIFFICULTY[`${pole.N}-${pole.C}`]} ${note(change)} ${note(decision)} ${note(help)} این سه مشاهده در نمره وارد نشده‌اند.`,
    learning: learningText(profile, pole),
    strengths: linesFor(profile, STRENGTHS),
    challenges: linesFor(profile, CHALLENGES),
    suggestions: suggestionsFor(pole),
    fun: funFor(profile.domains),
  };
}
